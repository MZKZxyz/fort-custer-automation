"""Draft-only GitHub App publisher. Worker never has this adapter or its token.

The public live entrypoint is code-blocked for this sprint. The complete sequence
is exercised through the same coordinator with a synthetic transport in CI.
"""
import base64
import json
import re
import subprocess
import urllib.error
import urllib.request
from trust import canonical, digest, require_live


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self,*args,**kwargs):
        return None


class AppGitHub:
    synthetic=False
    def __init__(self, installation_token, repository, mirror):
        if not installation_token or not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+',repository):
            raise ValueError('Scoped installation token and repository required')
        self.token,self.repository,self.mirror=installation_token,repository,mirror
        self.opener=urllib.request.build_opener(NoRedirect())

    def api(self, method, path, body=None):
        # Path is generated by this module only; untrusted issue text never enters URLs.
        request=urllib.request.Request('https://api.github.com/repos/'+self.repository+path,
            data=None if body is None else canonical(body).encode(),method=method,
            headers={'Authorization':'Bearer '+self.token,'Accept':'application/vnd.github+json',
                     'X-GitHub-Api-Version':'2022-11-28','Content-Type':'application/json'})
        try:
            with self.opener.open(request,timeout=20) as response:
                data=response.read(2*1024*1024+1)
                if len(data)>2*1024*1024:
                    raise ValueError('Oversized GitHub response')
                return json.loads(data)
        except Exception:
            raise ValueError('GitHub authentication/API failure; publication remains pending') from None

    def repository_id(self):
        response=self.api('GET','')
        if response.get('full_name')!=self.repository:
            raise ValueError('Destination repository mismatch')
        return response['full_name']

    def head(self,branch):
        # 404 is not silently treated as absence: GitHub API failure stays closed.
        refs=self.api('GET','/git/matching-refs/heads/'+branch)
        if not isinstance(refs,list) or len(refs)>1:
            raise ValueError('Ambiguous branch identity')
        if not refs:
            return None
        if refs[0]['ref']!='refs/heads/'+branch:
            raise ValueError('Branch identity mismatch')
        return refs[0]['object']['sha']

    def drafts(self,branch):
        prs=self.api('GET','/pulls?state=all&per_page=100&head='+self.repository.split('/')[0]+':'+branch)
        if not isinstance(prs,list) or len(prs)>=100:
            raise ValueError('Unverifiable PR pagination')
        return prs

    def push(self,branch,candidate):
        from independent_qa import git
        # mirror is a trusted bare ingestion mirror, never the worker's .git.
        if git(self.mirror,'rev-parse','--is-bare-repository').strip()!=b'true':
            raise ValueError('Trusted bare publication mirror required')
        url='https://github.com/'+self.repository+'.git'
        header='Authorization: Basic '+base64.b64encode(('x-access-token:'+self.token).encode()).decode()
        env={'PATH':'/usr/bin:/bin','HOME':'/nonexistent','GIT_CONFIG_NOSYSTEM':'1',
             'GIT_CONFIG_GLOBAL':'/dev/null','GIT_TERMINAL_PROMPT':'0',
             'GIT_CONFIG_COUNT':'1','GIT_CONFIG_KEY_0':'http.https://github.com/.extraheader',
             'GIT_CONFIG_VALUE_0':header}
        try:
            subprocess.run(['git','-C',str(self.mirror),'-c','core.hooksPath=/dev/null',
                            '-c','credential.helper=','push','--porcelain',
                            '--force-with-lease=refs/heads/'+branch+':',url,
                            candidate+':refs/heads/'+branch],env=env,check=True,capture_output=True,timeout=60)
        except Exception:
            raise ValueError('Branch push failed; inspect remote before retry') from None

    def create(self,branch,title,body):
        return self.api('POST','/pulls',dict(head=branch,base='main',title=title,body=body,
                                         draft=True,maintainer_can_modify=False))


class Publisher:
    def __init__(self,ledger,transport):
        self.ledger,self.transport=ledger,transport

    def publish(self,run,grant):
        if not self.ledger.synthetic or not self.transport.synthetic:
            require_live()
        # Durable outbox committed BEFORE network side effects. One approval can
        # authorize one publication operation; crash recovery resumes that outbox,
        # never consumes/reuses an approval or pushes another candidate.
        with self.ledger.tx() as db:
            self.ledger.enabled(db)
            r=self.ledger.get(db,run)
            if r['state']!='pr_ready' or not r['qa']:
                raise ValueError('Independent QA required')
            spec=json.loads(r['spec']); qa=json.loads(r['qa'])
            if qa['report']['candidate']!=r['candidate'] or qa['digest']!=digest(qa['report']):
                raise ValueError('Stale QA')
            self.ledger.validate_spec(spec)
            binding=self.ledger.request(spec,'publish',r['candidate'],qa['digest'])
            operator=self.ledger.verifier.consume(db,grant,'publish',binding,self.ledger.clock())
            db.execute("UPDATE s53_runs SET state='publishing' WHERE id=?",(run,))
            self.ledger.event(db,run,'publication_authorized',dict(operator=operator,binding=binding))
        return self.resume(run)

    def resume(self,run):
        if not self.ledger.synthetic or not self.transport.synthetic:
            require_live()
        import fcntl
        # Single-host durable authority. Never hold the database writer lock over
        # GitHub calls: kill switch and heartbeats must remain available.
        with open(str(self.ledger.path)+'.publication.lock','a') as lock:
            try:
                fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB)
            except BlockingIOError:
                raise ValueError('Publisher already active') from None
            return self._resume_locked(run)

    def _resume_locked(self,run):
        with self.ledger.tx() as db:
            self.ledger.enabled(db)
            r=self.ledger.get(db,run)
            if r['state']=='completed':
                return json.loads(r['pr'])
            if r['state']!='publishing':
                raise ValueError('Authorized publication outbox required')
            spec=json.loads(r['spec']); qa=json.loads(r['qa'])
            if qa['report']['candidate']!=r['candidate'] or qa['digest']!=digest(qa['report']):
                raise ValueError('Stale QA outbox')
            create_requested=bool(db.execute('SELECT 1 FROM s53_events WHERE run=? AND event="pr_create_requested"',(run,)).fetchone())
        if self.transport.repository_id()!=spec['repo']:
            raise ValueError('Source/destination repository mismatch')
        head=self.transport.head(spec['branch'])
        if head not in (None,r['candidate']):
            raise ValueError('Remote branch differs from reviewed candidate')
        existing=self.transport.drafts(spec['branch'])
        if len(existing)>1:
            raise ValueError('Duplicate PRs require human inspection')
        if existing:
            pr=existing[0]
            if head!=r['candidate']:
                raise ValueError('Existing PR remote branch missing or stale')
        else:
            if create_requested:
                # GitHub has no PR-create idempotency key. An empty list after
                # an ambiguous POST is not proof that the POST cannot complete.
                raise ValueError('Unresolved PR creation; authoritative human reconciliation required')
            with self.ledger.tx() as db:
                self.ledger.enabled(db)
            if head is None:
                self.transport.push(spec['branch'],r['candidate'])
            if self.transport.head(spec['branch'])!=r['candidate']:
                raise ValueError('Reviewed SHA not published')
            with self.ledger.tx() as db:
                self.ledger.enabled(db)
                self.ledger.event(db,run,'pr_create_requested',{'candidate':r['candidate']})
            pr=self.transport.create(spec['branch'],'Investigate '+spec['task'],
                'Issue: '+spec['task']+'\nExecution: '+run+'\nQA: '+qa['digest']+'\nReviewed SHA: '+r['candidate'])
        if (pr.get('state')!='open' or not pr.get('draft') or pr.get('merged') or pr.get('auto_merge')
                or pr.get('head',{}).get('sha')!=r['candidate']
                or pr.get('head',{}).get('ref')!=spec['branch']
                or pr.get('head',{}).get('repo',{}).get('full_name')!=spec['repo']
                or pr.get('base',{}).get('ref')!='main'
                or pr.get('base',{}).get('repo',{}).get('full_name')!=spec['repo']):
            raise ValueError('Draft PR identity/SHA mismatch')
        with self.ledger.tx() as db:
            current=self.ledger.get(db,run)
            if current['state']!='publishing' or current['candidate']!=r['candidate']:
                raise ValueError('Publication state changed; reconcile remote PR')
            db.execute("UPDATE s53_runs SET state='completed',pr=? WHERE id=?",(canonical(pr),run))
            self.ledger.event(db,run,'draft_published',dict(url=pr['html_url'],candidate=r['candidate']))
        return pr
